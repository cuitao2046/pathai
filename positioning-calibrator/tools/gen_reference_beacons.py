#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""由信标台账生成标定小程序参考数据（positioning-calibrator/data/reference_beacons.js）。

台账是坐标唯一来源（result/ble_deployment.json）。输出供小程序：
- 解析扫描三元组 (uuid, major, minor) → beaconId；
- 计算 truthDistanceM；
- 导出时写入 beaconLedgerSha256 与 mapVersion。

用法：
  python positioning-calibrator/tools/gen_reference_beacons.py
  python positioning-calibrator/tools/gen_reference_beacons.py --map-version 2026-10-27.9
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_LEDGER = PROJECT_ROOT / "result" / "ble_deployment.json"
DEFAULT_MAPS_DIR = PROJECT_ROOT / "backend" / "maps_data"
DEFAULT_OUT = PROJECT_ROOT / "positioning-calibrator" / "data" / "reference_beacons.js"
DEFAULT_VENUE = "school-building-01"


def load_json(path: Path) -> dict:
    with path.open(encoding="utf-8") as fp:
        return json.load(fp)


def latest_map_version(maps_dir: Path, venue_id: str) -> str:
    site_dir = maps_dir / venue_id
    candidates: list[tuple[str, str]] = []
    for path in site_dir.glob("*.json"):
        try:
            published = load_json(path).get("publishedAt") or ""
        except (json.JSONDecodeError, OSError):
            continue
        candidates.append((published, path.stem))
    if not candidates:
        raise SystemExit(f"没有可用的地图包：{site_dir}")
    return max(candidates)[1]


def build_reference(ledger: dict, venue_id: str, map_version: str, ledger_sha: str) -> dict:
    beacons = []
    triplets: set[tuple[str, int, int]] = set()
    ids: set[str] = set()
    uuids: set[str] = set()
    for raw in ledger.get("beacons") or []:
        beacon_id = raw.get("beaconId")
        coords = raw.get("coordinates")
        if not beacon_id or not isinstance(coords, list) or len(coords) != 2:
            raise SystemExit(f"台账信标缺字段：{beacon_id!r}")
        triplet = (str(raw.get("uuid") or ""), int(raw.get("major")), int(raw.get("minor")))
        if beacon_id in ids:
            raise SystemExit(f"台账 beaconId 重复：{beacon_id}")
        if triplet in triplets:
            raise SystemExit(f"台账三元组重复：{triplet}")
        ids.add(beacon_id)
        triplets.add(triplet)
        uuids.add(triplet[0])
        beacons.append({
            "beaconId": beacon_id,
            "floor": int(raw.get("floor")),
            "x": float(coords[0]),
            "y": float(coords[1]),
            "uuid": triplet[0],
            "major": triplet[1],
            "minor": triplet[2],
            "locationDesc": raw.get("locationDesc") or "",
        })
    return {
        "VENUE_ID": venue_id,
        "MAP_VERSION": map_version,
        "LEDGER_SHA256": ledger_sha,
        "WINDOW_MS": 2000,
        "UUIDS": sorted(uuids),
        "BEACONS": beacons,
    }


def render_js(ref: dict) -> str:
    body = json.dumps(ref, ensure_ascii=False, indent=2)
    return (
        "// AUTO-GENERATED by tools/gen_reference_beacons.py — do not edit.\n"
        "// 数据来源：result/ble_deployment.json（坐标唯一来源）\n"
        f"module.exports = {body}\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="生成标定小程序参考信标数据")
    parser.add_argument("--ledger", type=Path, default=DEFAULT_LEDGER)
    parser.add_argument("--maps-dir", type=Path, default=DEFAULT_MAPS_DIR)
    parser.add_argument("--venue-id", default=DEFAULT_VENUE)
    parser.add_argument("--map-version", default=None, help="缺省取 maps_data 下 publishedAt 最新的版本")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args(argv)

    ledger_bytes = args.ledger.read_bytes()
    ledger = json.loads(ledger_bytes.decode("utf-8"))
    map_version = args.map_version or latest_map_version(args.maps_dir, args.venue_id)
    ref = build_reference(
        ledger, args.venue_id, map_version, hashlib.sha256(ledger_bytes).hexdigest()
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render_js(ref), encoding="utf-8")
    print(
        f"已生成 {args.out.relative_to(PROJECT_ROOT)}："
        f"{len(ref['BEACONS'])} 枚信标 / mapVersion={map_version} / "
        f"ledgerSha256={ref['LEDGER_SHA256'][:12]}…"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
